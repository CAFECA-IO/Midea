def mentions(text: str) -> list[str]:
    """Actor ids mentioned as @handle (or @name) in `text`, in order of first appearance."""
    out: list[str] = []
    for m in HANDLE_RE.finditer(text or ""):
        tok = m.group(1).rstrip(".-")
        a = find(tok)
        while a is None and len(tok) > 1:          # '@林以安走進夜市' — CJK has no spaces: try shorter prefixes
            tok = tok[:-1]
            a = find(tok)
        if a and a.id not in out:
            out.append(a.id)
    return out


def resolve_list(refs: list[str] | None) -> list[str]:
    out: list[str] = []
    for r in refs or []:
        a = find(str(r))
        if a and a.id not in out:
            out.append(a.id)
    return out


def summary(a: Actor, films: list[dict] | None = None) -> dict:
    by_view = {p.view: p.file for p in a.portraits}
    thumb = by_view.get(a.primary) or (a.portraits[0].file if a.portraits else None)
    return {"id": a.id, "handle": a.handle, "name": a.name, "name_en": a.name_en, "age": a.age, "gender": a.gender,
            "occupation": a.occupation, "tags": a.tags, "thumb": thumb, "voice": bool(a.voice.sample),
            "real_person": a.consent.real_person, "jobs": a.jobs,
            "films": len(films) if films is not None else None}


def filmography(aid: str) -> list[dict]:
    """Every project that casts this actor, newest first, with the scenes they appear in."""
    out = []
    for f in sorted(settings().workspace.glob("*/project.json"), reverse=True):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            continue
        if aid not in (d.get("brief", {}).get("actors") or []):
            continue
        pdir = f.parent
        plan = _read(pdir / "stages" / "scene_plan.json") or {}
        assets = (_read(pdir / "stages" / "assets.json") or {}).get("scenes", {})
        prop = _read(pdir / "stages" / "proposal.json") or {}
        scenes, lines = [], 0
        for sc in plan.get("scenes", []):
            on = aid in (sc.get("actors") or [])
            speaks = sc.get("speaker") == aid
            lines += int(speaks)
            if on or speaks:
                scenes.append({"id": sc["id"], "on_screen": on, "speaks": speaks, "narration": sc.get("narration", "")[:80],
                               "thumb": (assets.get(sc["id"]) or {}).get("thumb")})
        items = (d.get("deliverables") or {}).get("items") or []
        thumb = items[0].get("thumbnail") if items else next((s["thumb"] for s in scenes if s.get("thumb")), None)
        role = "主演" if any(s["on_screen"] for s in scenes) else ("配音" if lines else "演出")
        out.append({"project": d["id"], "title": prop.get("title") or d.get("brief", {}).get("prompt", "")[:60],
                    "prompt": d.get("brief", {}).get("prompt", ""), "status": d.get("status"), "created": d.get("created"),
                    "pipeline": d.get("pipeline"), "role": role, "scenes": scenes, "lines": lines, "thumb": thumb,
                    "video": items[0].get("video") if items else None, "published": bool(items)})
    return out


def _read(p: Path) -> Any:
    try:
        return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None
    except Exception:  # noqa: BLE001
        return None
