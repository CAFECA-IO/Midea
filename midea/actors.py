# ---------------------------------------------------------------- data model
class _M(BaseModel):
    model_config = ConfigDict(extra="allow")

    @model_validator(mode="before")
    @classmethod
    def _drop_nulls(cls, v):
        return {k: x for k, x in v.items() if x is not None} if isinstance(v, dict) else v


class Appearance(_M):
    ethnicity: str = ""             # 外觀族裔 / 地區特徵
    height_cm: Optional[int] = None
    build: str = ""                 # 體型
    face: str = ""                  # 臉型、五官
    hair: str = ""
    eyes: str = ""
    skin: str = ""
    features: str = ""              # 辨識特徵：痣、眼鏡、疤…
    prompt_en: str = ""             # 給影像模型的英文外貌描述（由 AI 生成，可手改）

    @field_validator("height_cm", mode="before")
    @classmethod
    def _h(cls, v):
        if v in ("", None):
            return None
        m = re.search(r"\d{2,3}", str(v))
        return int(m.group(0)) if m else None


class Voice(_M):
    description: str = ""           # VoxCPM2 聲音設計描述（英文效果最佳）
    description_zh: str = ""
    language: str = "zh-TW"
    sample_text: str = ""
    sample: str = ""                # 相對於演員資料夾的 wav
    source: Literal["designed", "uploaded", "none"] = "none"
    mock: bool = False              # 以 mock 模式產生（真模型上線後自動重做）


class Consent(_M):
    real_person: bool = False       # 是否以真人肖像 / 聲音為基礎
    attested: bool = False          # 已勾選「已取得本人授權」
    by: str = ""
    at: float = 0
    note: str = ""                  # 授權來源 / 文件編號
    scope: list[str] = Field(default_factory=list)    # ["portrait", "voice"]


class Portrait(_M):
    view: str
    file: str
    seed: int = 0
    prompt: str = ""
    source: Literal["generated", "uploaded", "mock"] = "generated"
    at: float = 0


class Actor(_M):
    id: str = ""
    handle: str
    name: str
    name_en: str = ""
    age: int = 30
    gender: Literal["female", "male", "nonbinary"] = "female"
    nationality: str = ""
    occupation: str = ""
    appearance: Appearance = Field(default_factory=Appearance)
    wardrobe: str = ""              # 預設造型（中文）
    wardrobe_en: str = ""
    personality: str = ""
    bio: str = ""
    acting_notes: str = ""          # 表演風格、肢體習慣
    tags: list[str] = Field(default_factory=list)
    voice: Voice = Field(default_factory=Voice)
    portraits: list[Portrait] = Field(default_factory=list)
    primary: str = "headshot"
    seed: int = 0
    consent: Consent = Field(default_factory=Consent)
    jobs: dict = Field(default_factory=dict)        # {"portraits": {...}, "voice": {...}}
    cost: dict = Field(default_factory=lambda: {"actual": 0.0, "lines": []})
    created: float = 0
    updated: float = 0

    @field_validator("gender", mode="before")
    @classmethod
    def _gender(cls, v):
        s = str(v or "").strip().lower()
        if s in ("female", "f", "woman", "女", "女性", "女生"):
            return "female"
        if s in ("male", "m", "man", "男", "男性", "男生"):
            return "male"
        return "nonbinary" if s else "female"

    @field_validator("age", mode="before")
    @classmethod
    def _age(cls, v):
        m = re.search(r"\d{1,3}", str(v or ""))
        return max(1, min(100, int(m.group(0)))) if m else 30

    @field_validator("handle", mode="before")
    @classmethod
    def _handle(cls, v):
        return normalize_handle(v)

    @field_validator("tags", mode="before")
    @classmethod
    def _tags(cls, v):
        if isinstance(v, str):
            return [t.strip() for t in re.split(r"[,，、/\s]+", v) if t.strip()]
        return v or []


def normalize_handle(v: Any) -> str:
    s = unicodedata.normalize("NFKC", str(v or "")).strip().lstrip("@")
    s = re.sub(r"\s+", "_", s)
    s = re.sub(r"[^\w㐀-鿿぀-ヿ가-힯.\-]", "", s)
    return s[:32]


# ---------------------------------------------------------------- storage
def root() -> Path:
    p = settings().workspace / "_actors"
    p.mkdir(parents=True, exist_ok=True)
    return p


def adir(aid: str) -> Path:
    if not re.fullmatch(r"[a-z0-9_-]{3,40}", aid or ""):
        raise KeyError(aid)
    return root() / aid


def load(aid: str) -> Actor:
    f = adir(aid) / "actor.json"
    if not f.exists():
        raise KeyError(aid)
    return Actor(**json.loads(f.read_text(encoding="utf-8")))


def save(a: Actor) -> Actor:
    with _lock:
        a.updated = time.time()
        d = adir(a.id)
        d.mkdir(parents=True, exist_ok=True)
        tmp = d / "actor.tmp"
        tmp.write_text(a.model_dump_json(indent=1), encoding="utf-8")
        tmp.replace(d / "actor.json")
    return a


def update(aid: str, fn) -> Actor:
    with _lock:
        a = load(aid)
        fn(a)
        return save(a)


def list_all() -> list[Actor]:
    out = []
    for f in sorted(root().glob("*/actor.json")):
        try:
            out.append(Actor(**json.loads(f.read_text(encoding="utf-8"))))
        except Exception as e:  # noqa: BLE001
            log.warning("bad actor file %s: %s", f, e)
    return sorted(out, key=lambda a: -a.created)


def find(ref: str) -> Actor | None:
    """Resolve '@handle', a handle, an id or an exact name (case-insensitive)."""
    key = normalize_handle(ref).lower()
    if not key:
        return None
    for a in list_all():
        if key in (a.handle.lower(), a.id, normalize_handle(a.name).lower(), normalize_handle(a.name_en).lower()):
            return a
    return None


def _unique_handle(handle: str, exclude: str = "") -> str:
    base = normalize_handle(handle) or "actor"
    taken = {a.handle.lower() for a in list_all() if a.id != exclude}
    h, i = base, 2
    while h.lower() in taken:
        h, i = f"{base}{i}", i + 1
    return h


def create(data: dict) -> Actor:
    data = dict(data)
    data.setdefault("handle", data.get("name_en") or data.get("name") or "actor")
    a = Actor(**data)
    a.id = "a-" + uuid.uuid4().hex[:8]
    a.handle = _unique_handle(a.handle)
    a.seed = a.seed or zlib.crc32(a.id.encode()) % 2_000_000_000
    a.created = time.time()
    if a.consent.attested and not a.consent.at:
        a.consent.at = time.time()
    return save(a)


EDITABLE = {"handle", "name", "name_en", "age", "gender", "nationality", "occupation", "appearance", "wardrobe",
            "wardrobe_en", "personality", "bio", "acting_notes", "tags", "voice", "primary", "seed"}


def edit(aid: str, patch: dict) -> Actor:
    def f(a: Actor) -> None:
        cur = a.model_dump()
        for k, v in patch.items():
            if k not in EDITABLE:
                continue
            if k in ("appearance", "voice") and isinstance(v, dict):
                cur[k].update(v)
            else:
                cur[k] = v
        b = Actor(**cur)
        b.handle = _unique_handle(b.handle, exclude=a.id)
        for k in EDITABLE:
            setattr(a, k, getattr(b, k))
    return update(aid, f)


def delete(aid: str) -> None:
    d = adir(aid)
    trash = root() / "_trash"
    trash.mkdir(exist_ok=True)
    shutil.move(str(d), str(trash / f"{aid}-{int(time.time())}"))


# ---------------------------------------------------------------- prompts
_GENDER_EN = {"female": ("woman", "girl"), "male": ("man", "boy"), "nonbinary": ("person", "child")}


def person_en(a: Actor) -> str:
    adult, kid = _GENDER_EN[a.gender]
    noun = kid if a.age < 13 else ("teenage " + adult if a.age < 18 else adult)
    eth = a.appearance.ethnicity.strip()
    return f"{a.age}-year-old {eth + ' ' if eth and eth.isascii() else ''}{noun}"


def look_en(a: Actor) -> str:
    ap = a.appearance
    if ap.prompt_en.strip():
        return ap.prompt_en.strip().rstrip(".")
    bits = [x for x in (ap.build, ap.face, ap.hair, ap.eyes, ap.skin, ap.features) if x and x.isascii()]
    return ", ".join(bits)


def portrait_prompt(a: Actor, view: str) -> str:
    v = VIEWS[view]
    wardrobe = a.wardrobe_en or (a.wardrobe if a.wardrobe.isascii() else "")
    parts = [f"Photorealistic studio photograph of a {person_en(a)}", look_en(a),
             f"wearing {wardrobe}" if wardrobe else "", v["shot"],
             "plain light grey seamless studio backdrop, soft diffused key light with gentle rim light, "
             "85mm lens, sharp focus on the eyes, natural skin texture with pores, true-to-life colors, "
             "ultra detailed, no text, no watermark"]
    return ". ".join(p for p in parts if p)


def ref_images(a: Actor, views: list[str] | None = None) -> list[str]:
    """Absolute paths of the actor's reference photos for H3 Ref2VA (primary first)."""
    order = [a.primary] + [v for v in (views or REF_VIEWS) if v != a.primary]
    by_view = {p.view: p for p in a.portraits}
    out = [str(adir(a.id) / by_view[v].file) for v in order if v in by_view and (adir(a.id) / by_view[v].file).exists()]
    if not out and a.portraits:
        out = [str(adir(a.id) / a.portraits[0].file)]
    return out


def bible(a: Actor) -> dict:
    """Compact profile handed to the planner (LLM)."""
    return {"handle": "@" + a.handle, "name": a.name, "name_en": a.name_en, "age": a.age, "gender": a.gender,
            "nationality": a.nationality, "occupation": a.occupation,
            "look": look_en(a) or " ".join(filter(None, [a.appearance.face, a.appearance.hair, a.appearance.build])),
            "wardrobe": a.wardrobe_en or a.wardrobe, "personality": a.personality, "bio": a.bio[:400],
            "acting_notes": a.acting_notes, "voice": a.voice.description_zh or a.voice.description}


def voice_prompt(a: Actor) -> str:
    """VoxCPM2 voice-design control text (the part inside the leading parentheses)."""
    d = a.voice.description.strip() or a.voice.description_zh.strip()
    adult = {"female": "female", "male": "male", "nonbinary": "androgynous"}[a.gender]
    base = f"{a.age}-year-old {adult} voice"
    return f"{base}, {d}" if d else base


def default_sample_text(a: Actor) -> str:
    lang = (a.voice.language or "zh-TW").lower()
    if lang.startswith("en"):
        return (f"Hi, I'm {a.name_en or a.name}. It's a beautiful morning, and today I'd like to take you "
                f"somewhere you've never been before. Ready? Let's go.")
    if lang.startswith("ja"):
        return f"こんにちは、{a.name}です。今日はとてもいい天気ですね。一緒に、まだ見たことのない場所へ出かけましょう。"
    return f"大家好，我是{a.name}。今天的天氣很好，我想帶你去一個從來沒去過的地方，看看不一樣的風景。準備好了嗎？我們出發吧。"


