def add_upload(aid: str, kind: str, src: Path, *, consent: bool, note: str = "", by: str = "board",
               view: str = "headshot", transcript: str = "") -> Actor:
    if not consent:
        raise PermissionError("上傳真人照片或聲音前，必須勾選「已取得本人授權」")
    d = adir(aid)
    (d / "uploads").mkdir(parents=True, exist_ok=True)
    ext = src.suffix.lower()
    if kind == "portrait":
        if ext not in (".png", ".jpg", ".jpeg", ".webp"):
            raise ValueError("portrait must be an image")
        from .media import ff
        rel = f"portraits/{view}_upload_{int(time.time())}.png"
        (d / "portraits").mkdir(exist_ok=True)
        ff.run(["-i", src, "-frames:v", "1", d / rel])
    elif kind == "voice":
        from .media import ff
        rel = f"voice/upload_{int(time.time())}.wav"
        (d / "voice").mkdir(exist_ok=True)
        # clean 48 kHz mono reference, ≤ 20 s, leading/trailing silence trimmed
        ff.run(["-i", src, "-t", "20", "-ac", "1", "-ar", "48000", "-af",
                "silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
                "silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-20", d / rel])
    else:
        raise ValueError(kind)
    shutil.copy(src, d / "uploads" / src.name)

    def f(a: Actor) -> None:
        a.consent.real_person = True
        a.consent.attested = True
        a.consent.by = by
        a.consent.at = time.time()
        a.consent.note = note or a.consent.note
        a.consent.scope = sorted(set(a.consent.scope) | {kind})
        if kind == "portrait":
            a.portraits = [p for p in a.portraits if p.view != view] + [Portrait(view=view, file=rel, source="uploaded", at=time.time())]
        else:
            a.voice.sample, a.voice.source = rel, "uploaded"
            a.voice.sample_text = transcript or a.voice.sample_text
    return update(aid, f)


