"""Virtual actors: persistent, photoreal characters you can cast in any video with @handle.

An actor bundles a full profile (age, gender, look, wardrobe, personality, voice), a set of
costume photos generated by Z-Image-Turbo (front headshot, three-quarter, profile, full body)
and a voice sample designed with VoxCPM2. When a brief mentions @handle:

  * the planner receives the actor's bible and writes them into the script / shots;
  * shots that show the actor use MiniMax H3 Ref2VA with the actor's photos as references,
    so the face and outfit stay the same across shots and across videos;
  * lines the actor speaks are cloned from the actor's voice sample (VoxCPM2);
  * the actor page lists every video the actor appears in (filmography).

Real people: uploading photos / voice of a real person requires an explicit consent
attestation, which is stored with the actor and shown on the profile page.

Storage: <workspace>/_actors/<id>/actor.json, portraits/*.png, voice/sample.wav, uploads/.
"""
